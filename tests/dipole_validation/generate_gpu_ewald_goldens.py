    ("noncubic_2x3x1", (2, 3, 1),
     ((6.0, 0.0, 0.0), (0.0, 9.0, 0.0), (0.0, 0.0, 3.0)),
     (((0.20, -0.40, 0.10), (0.23, -0.38, 0.09),
       (0.26, -0.36, 0.08), (0.29, -0.34, 0.07),
       (0.32, -0.32, 0.06), (0.35, -0.30, 0.05)),)),
    # h[1]=0.45 and h[5]=0.35 intentionally differ.  The legacy h[5]
    # cofactor typo cannot pass the reciprocal identity for this fixture.
