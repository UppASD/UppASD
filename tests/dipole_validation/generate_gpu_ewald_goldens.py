def positions(grid, cell):
    # C++/GPU contract: n1 fastest, then n2, then n3.
    return tuple(cell_vector(cell, (x / grid[0], y / grid[1], z / grid[2]))
                 for z in range(grid[2]) for y in range(grid[1]) for x in range(grid[0]))


def literal(value: float) -> str:
    return f"{value:.17g}"


def main() -> None:
    print("// Generated by generate_gpu_ewald_goldens.py; DO NOT edit by hand.")
    print("// Oracle: periodic_ewald_reference.evaluate_converged, tol=1e-13, max_shell=16.")
    print("#pragma once\n\n#include <array>\n#include <cstddef>\n\nnamespace gpu_ewald_golden_v1 {\n")
    print("struct Case { const char* name; std::array<std::size_t, 3> grid; std::array<double, 9> H; std::size_t ensembles; const double* moments; const double* fields; const double* energies; };\n")
    entries = []
    for number, (name, grid, cell, ensemble_moments) in enumerate(CASES):
        all_fields = []
        energies = []
        for moments in ensemble_moments:
            result = evaluate_converged(positions(grid, cell), moments, cell, tolerance=1e-13, max_shell=16)
            all_fields.extend(component for field in result.fields for component in field)
            energies.append(result.energy)
        moments_flat = [component for ensemble in ensemble_moments for moment in ensemble for component in moment]
        h_flat = [component for vector in cell for component in vector]
        print(f"inline constexpr std::array<double, {len(h_flat)}> h_{number}{{{{{', '.join(map(literal, h_flat))}}}}};")
        print(f"inline constexpr std::array<double, {len(moments_flat)}> moments_{number}{{{{{', '.join(map(literal, moments_flat))}}}}};")
        print(f"inline constexpr std::array<double, {len(all_fields)}> fields_{number}{{{{{', '.join(map(literal, all_fields))}}}}};")
        print(f"inline constexpr std::array<double, {len(energies)}> energies_{number}{{{{{', '.join(map(literal, energies))}}}}};\n")
        entries.append((name, grid, len(ensemble_moments), number))
    print("inline constexpr std::array<Case, %d> cases{" % len(entries))
    for name, grid, ensembles, number in entries:
        print(f'   Case{{"{name}", {{{grid[0]}, {grid[1]}, {grid[2]}}}, h_{number}, {ensembles}, moments_{number}.data(), fields_{number}.data(), energies_{number}.data()}},')
    print("};\n} // namespace gpu_ewald_golden_v1")


if __name__ == "__main__":
    main()
